/**
 * Native writes through triggers, under the writer's native-step floors. Trigger bodies write a
 * second table row by row (native INSERT, UPDATE and DELETE) for root statements over many and
 * wide rows, at the suite's cap; PostgreSQL is the authority for the resulting rows. A root may be
 * refused with 53200 only when its need exceeds the cap. Growth the native steps request is counted
 * and reported. Sequence-backed values in a trigger body (nextval, identity, serial) are refused by
 * the executor (0A000) before any row is written.
 */
import { PGlite } from "@electric-sql/pglite";
import fc from "fast-check";
import { expect, it } from "vitest";
import { seedsFor } from "../../testing/seeds.js";
import {
  createReach,
  NATIVE_WRITE_FLOORS_LARGE_REACH,
  NATIVE_WRITE_FLOORS_REACH,
} from "../../testing/reach.js";
import { MinnowDatabaseClient } from "../owner/database-client.js";
import { publicOwner } from "./public-owner.test.fixture.js";

const capBytes = (process.env.MINNOW_TRIGGER_CAP_MIB === "32" ? 32 : 64) << 20;

// Trigger INSERT bodies write a keyless table; UPDATE and DELETE bodies a keyed one (the shipped
// native body surface).
const BODIES = [
  { name: "copy", event: "INSERT", sql: "INSERT INTO log VALUES(NEW.id,NEW.v)", ret: "NEW" },
  { name: "follow", event: "UPDATE", sql: "UPDATE mirror SET v=NEW.v WHERE id=NEW.id", ret: "NEW" },
  { name: "drop", event: "DELETE", sql: "DELETE FROM mirror WHERE id=OLD.id", ret: "OLD" },
] as const;

it("refuses sequence-backed values in a trigger body before writing anything", async () => {
  const owner = await publicOwner({ capBytes });
  const db = new MinnowDatabaseClient(owner.client, { ready: Promise.resolve() });
  try {
    await db.execute("CREATE TABLE t(id INT PRIMARY KEY)");
    await db.execute("CREATE TABLE a(n BIGINT, id INT)");
    await db.execute("CREATE TABLE u(id INT PRIMARY KEY)");
    await db.execute("CREATE TABLE b(n BIGINT GENERATED BY DEFAULT AS IDENTITY, id INT)");
    await db.execute("CREATE SEQUENCE s");
    await db.execute(
      "CREATE TRIGGER r AFTER INSERT ON t FOR EACH ROW BEGIN INSERT INTO a VALUES(nextval('s'),NEW.id); END",
    );
    await expect(db.execute("INSERT INTO t VALUES(1)")).rejects.toMatchObject({
      sqlState: "0A000",
    });
    await db.execute(
      "CREATE TRIGGER q AFTER INSERT ON u FOR EACH ROW BEGIN INSERT INTO b(id) VALUES(NEW.id); END",
    );
    await expect(db.execute("INSERT INTO u VALUES(1)")).rejects.toMatchObject({
      sqlState: "0A000",
    });
    // Atomic: neither the root row nor any body row.
    for (const table of ["t", "u", "a", "b"])
      expect((await db.query(`SELECT count(*) AS n FROM ${table}`)).rows()).toEqual([{ n: 0 }]);
  } finally {
    await db.close();
    await owner.close();
  }
  expect(owner.core.harness.governor.usedBytes).toBe(0);
});

/** One history: native writes through triggers, compared with PostgreSQL row for row. A root
 * statement may instead be refused with 53200 when the native root and the writer's mandatory
 * workspace exceed the cap; it is then atomic (nothing written) and PostgreSQL skips it too. */
async function history(
  pg: PGlite,
  reach: { beginHistory(): void; reach(state: string): void },
  declared: readonly string[],
  [rows, width, every, published]: [number, number, number, boolean],
): Promise<number> {
  reach.beginHistory();
  // Marks a state only where the calling test declared it (the unit and large lanes differ).
  const mark = (state: string) => {
    if (declared.includes(state)) reach.reach(state);
  };
  const wide = (fill: string) => fill.repeat(width);
  const owner = await publicOwner({ capBytes }),
    db = new MinnowDatabaseClient(owner.client, { ready: Promise.resolve() }),
    governor = owner.core.harness.governor;
  let grows = 0;
  const admitGroup = governor.admitGroup.bind(governor);
  governor.admitGroup = (options) => {
    if (options.label.startsWith("complete grow")) grows++;
    return admitGroup(options);
  };
  try {
    await pg.exec("DROP TABLE IF EXISTS t,log,mirror CASCADE");
    for (const sql of [
      "CREATE TABLE t(id INT PRIMARY KEY,v TEXT)",
      "CREATE TABLE log(id INT,v TEXT)",
      "CREATE TABLE mirror(id INT PRIMARY KEY,v TEXT)",
      `INSERT INTO mirror SELECT g, 'm' FROM generate_series(1, ${String(rows)}) g`,
    ]) {
      await db.execute(sql);
      await pg.exec(sql);
    }
    for (const body of BODIES) {
      await db.execute(
        `CREATE TRIGGER ${body.name} AFTER ${body.event} ON t FOR EACH ROW BEGIN ${body.sql}; END`,
      );
      await pg.exec(
        `CREATE OR REPLACE FUNCTION f_${body.name}() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN ${body.sql}; RETURN ${body.ret}; END $$; CREATE TRIGGER ${body.name} AFTER ${body.event} ON t FOR EACH ROW EXECUTE FUNCTION f_${body.name}()`,
      );
    }
    // Wide text is bound as a parameter: the same statement and value for both engines.
    const statements: Array<{ kind: string; sql: string; params: string[] }> = [
      {
        kind: "native insert",
        sql: `INSERT INTO t SELECT g, $1 || g::text FROM generate_series(1, ${String(rows)}) g`,
        params: [wide("x")],
      },
      {
        kind: "native update",
        sql: `UPDATE t SET v = $1 || (id * 7)::text WHERE id % ${String(every)} = 0`,
        params: [wide("y")],
      },
      {
        kind: "native delete",
        sql: `DELETE FROM t WHERE id % ${String(every + 1)} = 1`,
        params: [],
      },
    ];
    for (const [k, { kind, sql, params }] of statements.entries()) {
      let refused: unknown = null;
      try {
        await db.execute(sql, params);
      } catch (error) {
        refused = error;
      }
      if (refused === null) {
        await pg.query(sql, params);
        mark(kind);
      } else {
        // Only a typed refusal above the cap is lawful here; the statement wrote nothing.
        expect(refused).toMatchObject({ sqlState: "53200" });
        expect((refused as { bytes: number }).bytes).toBeGreaterThan(
          (refused as { capacity: number }).capacity,
        );
        mark("native root refused above the cap");
      }
      if (k === 0 && published) {
        await owner.core.harness.path.recycleLog();
        await owner.core.harness.path.quiesce();
        mark("published before update and delete");
      }
    }
    for (const query of [
      "SELECT * FROM t ORDER BY id",
      "SELECT * FROM log ORDER BY id, v",
      "SELECT * FROM mirror ORDER BY id",
    ])
      expect((await db.query(query)).rows(), query).toEqual((await pg.query(query)).rows);
    if (rows >= 20_000) mark("large native insert");
    if (width >= 1_000) mark("wide rows");
    if (grows > 0) mark("growth requested by native steps");
    mark("PG exact rows");
  } finally {
    governor.admitGroup = admitGroup;
    await db.close();
    await owner.close();
  }
  expect(governor.usedBytes).toBe(0);
  return grows;
}

/** Records the growth requests each history made (MINNOW_NATIVE_GROWTH_LOG, for the floors bench). */
async function logGrowth(seed: number, growth: readonly number[]): Promise<void> {
  const log = process.env.MINNOW_NATIVE_GROWTH_LOG;
  if (log !== undefined && log.length > 0)
    (await import("node:fs")).appendFileSync(log, `${String(seed)} ${growth.join(",")}\n`);
}

// Unit shard: histories a shard can afford (at most 1,000 root rows).
for (const seed of seedsFor("next-native-write-floors", [51011, 51012]))
  it(`matches PostgreSQL for native writes under the writer floors (${String(seed)})`, async () => {
    const pg = new PGlite(),
      reach = createReach("native writes under the writer floors", NATIVE_WRITE_FLOORS_REACH);
    const growth: number[] = [];
    try {
      await fc.assert(
        fc.asyncProperty(
          fc.constantFrom(100, 500, 1_000),
          fc.constantFrom(8, 200, 1_000),
          fc.integer({ min: 2, max: 5 }),
          fc.boolean(),
          async (rows, width, every, published) => {
            growth.push(
              await history(pg, reach, NATIVE_WRITE_FLOORS_REACH, [rows, width, every, published]),
            );
          },
        ),
        {
          seed,
          numRuns: 5,
          examples: [
            [1_000, 1_000, 2, false],
            [500, 8, 3, true],
          ],
        },
      );
      reach.assertReached();
    } finally {
      await pg.close();
      await logGrowth(seed, growth);
    }
  }, 600_000);

// Conformance lane (.github/workflows/sql-conformance.yml, nightly and check:release): 20,000-row
// histories, too slow for a unit shard (about six minutes together). They finish because a trigger
// statement's cost per row no longer grows with its rows: a body's keyed read sizes from memtable
// summaries (write/memtable.ts), and commit encoding is linear in the undo log
// (write/stream-body.ts).
it.runIf(process.env.MINNOW_NATIVE_WRITE_LARGE === "1")(
  "matches PostgreSQL for large native writes under the writer floors",
  async () => {
    const pg = new PGlite(),
      reach = createReach(
        "large native writes under the writer floors",
        NATIVE_WRITE_FLOORS_LARGE_REACH,
      );
    const growth: number[] = [];
    try {
      for (const shape of [
        [20_000, 8, 2, false],
        [20_000, 1_000, 3, true],
      ] as const)
        growth.push(await history(pg, reach, NATIVE_WRITE_FLOORS_LARGE_REACH, [...shape]));
      reach.assertReached();
    } finally {
      await pg.close();
      await logGrowth(0, growth);
    }
  },
  3_600_000,
);
