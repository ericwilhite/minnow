/**
 * INSERT targets against PostgreSQL (PGlite): which columns a row's values go to, and which
 * statements are refused.
 *
 * Found 2026-11-23 (pure SQL on main 0911b2f0): `INSERT INTO t VALUES (100, 1, 'b')` into a table
 * of four columns was refused 42601 ("INSERT has more target columns than expressions"), and so was
 * `INSERT INTO t SELECT id, k, v FROM …` and a MERGE `INSERT VALUES` with fewer values; a MERGE
 * `INSERT VALUES` with more values than columns dropped the extra values.
 *
 * Law: PostgreSQL's INSERT (transformInsertStmt, transformInsertRow; docs "INSERT": "The target
 * column names can be listed in any order. If no list of column names is given at all, the
 * default is all the columns of the table in their declared order; or the first N column names,
 * if there are only N columns supplied by the VALUES clause or query. … Each column not present
 * in the explicit or implicit column list will be filled with a default value"). More expressions
 * than target columns is 42601, fewer than an explicit list is 42601, VALUES lists of different
 * lengths are 42601 ("VALUES lists must all be the same length"); a non-DEFAULT value for a
 * generated or ALWAYS identity column is 428C9.
 *
 * Every statement runs on PostgreSQL, on the lowering through the IR reference interpreter (the
 * lowering is where targets are chosen), and on the composed engine through the protocol until
 * the engine meets a limit it has alone (identity defaults: `nextval` is not executed yet; MERGE
 * is not executed yet), after which that history compares the reference only.
 *
 * The explicit-list mismatch is refused by the shared parser (engine/query.ts) with 42601 and its
 * own wording ("Each INSERT row must match the column list length", "MERGE INSERT values must
 * match its column list", "INSERT ... SELECT must produce exactly the insert column count"), which the 0.x engine's tests assert: there the SQLSTATE is compared,
 * not the message.
 */
