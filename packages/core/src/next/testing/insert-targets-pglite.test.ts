type Reach = ReturnType<typeof createReach<(typeof INSERT_TARGETS_REACH)[number]>>;

interface Column {
  readonly name: string;
  readonly type: "int" | "text";
  readonly kind: "key" | "plain" | "generated" | "always" | "byDefault";
}

const TABLES: Record<string, { readonly create: string; readonly columns: readonly Column[] }> = {
  t: {
    create:
      "CREATE TABLE t (id integer PRIMARY KEY, a integer DEFAULT 5, b text DEFAULT 'x', g integer GENERATED ALWAYS AS (a * 2) STORED, c integer)",
    columns: [
      { name: "id", type: "int", kind: "key" },
      { name: "a", type: "int", kind: "plain" },
      { name: "b", type: "text", kind: "plain" },
      { name: "g", type: "int", kind: "generated" },
      { name: "c", type: "int", kind: "plain" },
    ],
  },
  u: {
    create:
      "CREATE TABLE u (id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY, a integer DEFAULT 7, b text)",
    columns: [
      { name: "id", type: "int", kind: "always" },
      { name: "a", type: "int", kind: "plain" },
      { name: "b", type: "text", kind: "plain" },
    ],
  },
  w: {
    create:
      "CREATE TABLE w (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, a integer, b text DEFAULT 'y')",
    columns: [
      { name: "id", type: "int", kind: "byDefault" },
      { name: "a", type: "int", kind: "plain" },
      { name: "b", type: "text", kind: "plain" },
    ],
  },
};
const NAMES = Object.keys(TABLES);

interface Statement {
  readonly table: string;
  readonly form: "values" | "select" | "default values" | "merge";
  /** Positions into the table's columns, or null for no column list. */
  readonly list: readonly number[] | null;
  /** Values per row; later rows may differ (ragged). */
  readonly widths: readonly number[];
  /** Per row and position: a DEFAULT cell. */
  readonly defaults: ReadonlyArray<readonly boolean[]>;
}

const statement: fc.Arbitrary<Statement> = fc
  .record({
    table: fc.constantFrom(...NAMES),
    form: fc.constantFrom<Statement["form"]>(
      "values",
      "values",
      "values",
      "select",
      "default values",
      "merge",
    ),
    explicit: fc.boolean(),
    order: fc.array(fc.nat(9), { minLength: 5, maxLength: 5 }),
    take: fc.integer({ min: 1, max: 5 }),
    delta: fc.constantFrom(-1, 0, 0, 0, 1),
    width: fc.integer({ min: 1, max: 6 }),
    rows: fc.integer({ min: 1, max: 3 }),
    ragged: fc.array(fc.constantFrom(0, 0, 0, -1, 1), { minLength: 3, maxLength: 3 }),
    defaults: fc.array(fc.array(fc.boolean(), { minLength: 7, maxLength: 7 }), {
      minLength: 3,
      maxLength: 3,
    }),
    dense: fc.boolean(),
  })
  .map((g): Statement => {
    const columns = TABLES[g.table]?.columns ?? [];
    // An explicit list: a reordering of some of the table's columns.
    const positions = columns
      .map((_, k) => k)
      .sort((x, y) => (g.order[x] ?? 0) - (g.order[y] ?? 0) || x - y)
      .slice(0, Math.min(g.take, columns.length));
    const list = g.explicit && g.form !== "default values" ? positions : null;
    const base =
      list === null ? Math.min(g.width, columns.length + 1) : Math.max(1, list.length + g.delta);
    const rows = g.form === "values" ? g.rows : 1;
    const widths = Array.from({ length: rows }, (_, k) =>
      Math.max(1, base + (k === 0 ? 0 : (g.ragged[k] ?? 0))),
    );
    return {
      table: g.table,
      form: g.form,
      list,
      widths,
      // Sparse DEFAULT cells, or many (so a generated or ALWAYS column often gets DEFAULT).
      defaults: g.defaults.map((row) => row.map((cell, k) => cell && (g.dense || k % 3 === 0))),
    };
  });

/** The SQL of `s`, with fresh key values from `next`. */
function render(s: Statement, next: () => number): string {
  const table = TABLES[s.table];
  if (table === undefined) throw new Error(s.table);
  if (s.form === "default values") return `INSERT INTO ${s.table} DEFAULT VALUES`;
  const targets = (s.list ?? table.columns.map((_, k) => k)).map((k) => table.columns[k]);
  const list =
    s.list === null ? "" : ` (${s.list.map((k) => table.columns[k]?.name ?? "").join(", ")})`;
  const cell = (row: number, position: number): string => {
    const column = targets[position];
    if (s.form !== "select" && s.defaults[row]?.[position] === true) return "DEFAULT";
    if (column?.type === "text") return `'v${String(next())}'`;
    return String(next());
  };
  const row = (k: number) =>
    Array.from({ length: s.widths[k] ?? 0 }, (_, position) => cell(k, position)).join(", ");
  if (s.form === "select") return `INSERT INTO ${s.table}${list} SELECT ${row(0)}`;
  if (s.form === "merge")
    return `MERGE INTO ${s.table} USING (SELECT ${String(next())} AS k) s ON ${s.table}.id = s.k WHEN NOT MATCHED THEN INSERT${list} VALUES (${row(0)})`;
  return `INSERT INTO ${s.table}${list} VALUES ${s.widths.map((_, k) => `(${row(k)})`).join(", ")}`;
}

/** The statement's outcome as compared: `ok`, or its SQLSTATE and (for these) message. */
function outcome(code: string, message: string, explicit: boolean): string {
  // The shared parser's own wording for an explicit-list mismatch (see the header).
  if (
    explicit &&
    code === "42601" &&
    /^(INSERT has more (target columns|expressions) than|VALUES lists must all|Each INSERT row must match|MERGE INSERT values must match|INSERT \.\.\. SELECT must produce exactly the insert column count)/u.test(
      message,
    )
  )
    return "42601 column list mismatch";
  return code === "42601" || code === "428C9" ? `${code} ${message}` : code;
}

function noteReach(s: Statement, authority: string, reach: Reach): void {
  const table = TABLES[s.table];
  if (table === undefined) return;
  const width = s.widths[0] ?? 0;
  const ragged = s.widths.some((w) => w !== width);
  if (ragged) reach.reach("ragged values");
  if (s.form === "default values") reach.reach("default values");
  if (s.form === "select") reach.reach("insert select");
  if (s.form === "merge") reach.reach("merge insert");
  if (s.list === null && s.form !== "default values") {
    if (width < table.columns.length) reach.reach("no list, fewer values");
    if (width > table.columns.length) reach.reach("no list, more values");
  }
  if (s.list !== null && width !== s.list.length) reach.reach("explicit list mismatch");
  if (s.defaults.some((row) => row.includes(true)) && s.form !== "select")
    reach.reach("default keyword");
  if (table.columns.some((c) => c.kind === "generated") && s.list === null)
    reach.reach(width > 3 ? "generated column supplied" : "generated column omitted");
  if (table.columns.some((c) => c.kind === "always")) reach.reach("identity always");
  if (table.columns.some((c) => c.kind === "byDefault")) reach.reach("identity by default");
  if (authority === "ok") reach.reach("served");
  else if (authority.startsWith("428C9")) reach.reach("refused 428C9");
  else if (authority.startsWith("42601")) reach.reach("refused 42601");
}

let pg: PGlite;
beforeAll(async () => {
  pg = new PGlite();
  await pg.waitReady;
});
afterAll(async () => {
  await pg.close();
});

async function history(statements: readonly Statement[], reach: Reach): Promise<void> {
  for (const name of NAMES) await pg.exec(`DROP TABLE IF EXISTS ${name}`);
  const reference = new LoweredDatabase();
  const h = new Harness("strict", "memory");
  await h.open();
  const engine = composeEngine({
    planner: createLowerer(),
    writePath: h.path,
    governor: h.governor,
    spill: new MemorySpillService(),
    reads: chunkReads,
  });
  const server = new OwnerServer(engine, { ownerId: "insert-targets", epoch: 1, build: "test" });
  const { port1, port2 } = new MessageChannel();
  server.accept(port1);
  const client = new ProtocolClient();
  await client.connect(port2);
  let key = 1000;
  const next = () => ++key;
  // The engine is compared until it meets a limit it has alone (header); the reference always.
  let engineCompared = true;
  try {
    for (const name of NAMES) {
      const create = TABLES[name]?.create ?? "";
      await pg.exec(create);
      reference.execute(create);
      await client.query(create);
    }
    for (const s of statements) {
      const sql = render(s, next);
      const explicit = s.list !== null;
      const authority = await pg.exec(sql).then(
        () => "ok",
        (error: unknown) =>
          outcome(String((error as { code?: unknown }).code), (error as Error).message, explicit),
      );
      const lowered = (() => {
        try {
          reference.execute(sql);
          return "ok";
        } catch (error) {
          const state = (error as { sqlState?: unknown }).sqlState;
          return outcome(String(state), (error as Error).message, explicit);
        }
      })();
      expect(lowered, `${sql}: the lowering`).toBe(authority);
      noteReach(s, authority, reach);
      const rows = async () =>
        (await pg.query(`SELECT * FROM ${s.table} ORDER BY id`)).rows.map((row) =>
          Object.values(row as Record<string, unknown>),
        );
      expect(
        reference
          .execute(`SELECT * FROM ${s.table} ORDER BY id`)
          .map((row) => Object.values(row).map((value) => comparable(value as never))),
        `${sql}: the reference's rows`,
      ).toEqual(await rows());
      if (!engineCompared) continue;
      const served = await client.query(sql).then(
        () => "ok",
        (error: unknown) =>
          outcome(
            String((error as { sqlState?: unknown }).sqlState),
            (error as Error).message,
            explicit,
          ),
      );
      if (
        served.startsWith("0A000") &&
        /nextval|modify kind/u.test(
          await client.query(sql).then(
            () => "",
            (error: unknown) => (error as Error).message,
          ),
        )
      ) {
        engineCompared = false;
        reach.reach("engine limit met");
        continue;
      }
      expect(served, `${sql}: the engine`).toBe(authority);
      const engineRows = (await client.query(`SELECT * FROM ${s.table} ORDER BY id`)).rows();
      expect(engineRows, `${sql}: the engine's rows`).toEqual(await rows());
      reach.reach("engine compared");
    }
  } finally {
    client.close();
    const stop = server.quiesce("closing");
    await stop.drained;
    stop.finish();
    port1.close();
    port2.close();
    await engine.close();
    await h.close();
  }
}

/** The reported statements, as the generator writes them. */
const REPORTED: readonly Statement[] = [
  { table: "t", form: "values", list: null, widths: [3], defaults: [[]] },
  { table: "t", form: "select", list: null, widths: [2], defaults: [[]] },
  { table: "t", form: "merge", list: null, widths: [2], defaults: [[]] },
  { table: "t", form: "merge", list: null, widths: [6], defaults: [[]] },
  { table: "t", form: "values", list: null, widths: [2, 3], defaults: [[], []] },
];

for (const seed of seedsFor("next-insert-targets", [0x1e01, 0x1e02]))
  it(`chooses INSERT targets as PostgreSQL does (seed ${String(seed)})`, async () => {
    const reach = createReach("INSERT targets", INSERT_TARGETS_REACH);
    await fc.assert(
      fc.asyncProperty(fc.array(statement, { minLength: 1, maxLength: 6 }), async (statements) => {
        reach.beginHistory();
        await history(statements, reach);
      }),
      { seed, numRuns: 40, examples: [[REPORTED]] },
    );
    reach.assertReached();
  }, 600_000);
