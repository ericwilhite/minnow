/** Retained byte extrema can grow several times within one group's private progress lane. */
import { PGlite } from "@electric-sql/pglite";
import fc from "fast-check";
import { afterAll, beforeAll, expect, it } from "vitest";
import { createReach } from "../../../testing/reach.js";
import { seedsFor } from "../../../testing/seeds.js";
import { Governor } from "../../memory/governor.js";
import { StepLoans } from "../../memory/step-loans.js";
import { ReservedGrant } from "../admission.js";
import { MemorySpillService } from "../../spill/memory-spill.js";
import { TEXT, F64, col, texts, numbers, valueAt } from "../kernels/test-support.js";
import { OutputArena } from "../kernels/vectors.js";
import { ExternalCall, externalCallMinimum } from "./external-call.js";
import { SortGrants } from "./sort-grants.js";

let pg: PGlite;
beforeAll(async () => {
  pg = new PGlite();
  await pg.waitReady;
}, 60000);
afterAll(async () => {
  await pg.close();
});
it.each(seedsFor("aggregate-external-growing-bytes", [0xb49f, 0xb4a0]))(
  "resizes retained extrema with all shared headroom pinned (seed %i)",
  async (seed) => {
    const reach = createReach("external aggregation byte progress", [
      "MIN",
      "MAX",
      "multiple growths",
      "private loan",
      "PG",
      "returned all credit",
    ]);
    await fc.assert(
      fc.asyncProperty(fc.integer({ min: 200000, max: 300000 }), async (width) => {
        reach.beginHistory();
        for (const fn of ["min", "max"] as const) {
          const call = {
            fn,
            args: [col(0, TEXT)],
            type: TEXT,
            distinct: false,
            filter: null,
            orderBy: [],
          };
          const minimum = externalCallMinimum(call),
            progress = Math.max(1 << 20, 4 * width),
            governor = new Governor(16 << 20);
          const parts = await governor.admitGroup({
            label: "external byte group",
            includesProgress: true,
            grants: [
              { label: "fixed", minimumBytes: minimum, spillable: false },
              { label: "progress", minimumBytes: progress, spillable: false },
              { label: "growth", minimumBytes: 0, spillable: true },
            ],
          });
          const fixed = parts[0],
            lane = parts[1],
            extra = parts[2];
          if (!fixed || !lane || !extra) throw new Error("Missing private byte lane");
          const step = new StepLoans(lane, progress, "byte transition");
          let loans = 0;
          const borrow = step.borrow.bind(step);
          step.borrow = (...args) => {
            loans++;
            return borrow(...args);
          };
          const owner = new ReservedGrant(lane, extra, 0, step, true);
          const grants = new SortGrants(fixed, [owner]),
            arena = new OutputArena(fixed, 2048),
            spill = new MemorySpillService();
          const pinned = await governor.admitGroup({
            label: "other execution pinned minimum",
            includesProgress: true,
            grants: [
              {
                label: "pinned",
                minimumBytes: governor.capBytes - minimum - progress,
                spillable: false,
              },
            ],
          });
          const state = new ExternalCall(
            call,
            {
              grants,
              context: { arena, input: [TEXT], params: { slots: [] } },
              check: () => {
                expect(governor.usedBytes).toBe(governor.capBytes);
              },
              pace: () => Promise.resolve(),
              sortContext: (grant) => ({ grant, spill, queryId: 1 }),
            },
            0,
          );
          try {
            const values = [0, 1, 2].map((i) =>
              String.fromCharCode(fn === "min" ? 122 - i : 97 + i).repeat(
                Math.floor(width / (i === 0 ? 4 : i === 1 ? 2 : 1)),
              ),
            );
            for (let i = 0; i < values.length; i++) {
              const value = values[i];
              if (value === undefined) throw new Error("missing generated byte value");
              await state.add(
                { length: 1, selection: null, columns: [texts([value])] },
                0,
                1,
                numbers(F64, [i]),
              );
            }
            const result = await pg.query<{ v: string }>(
              `SELECT ${fn}(v) v FROM (VALUES ($1::text),($2::text),($3::text)) t(v)`,
              values,
            );
            expect(valueAt(await state.emit(), 0)).toBe(result.rows[0]?.v);
            expect(loans).toBeGreaterThan(0);
            reach.reach("private loan");
            reach.reach("multiple growths");
            reach.reach("PG");
            reach.reach(fn === "min" ? "MIN" : "MAX");
          } finally {
            state.abort(new Error("test cleanup"));
            await state.close();
            arena.close();
            expect(parts.reduce((n, part) => n + part.allocated, 0)).toBe(0);
            grants.close();
            owner.close();
            step.close();
            for (const part of parts) part.close();
            for (const holder of pinned) holder.close();
          }
          expect(governor.usedBytes).toBe(0);
          reach.reach("returned all credit");
        }
      }),
      { seed, numRuns: 3 },
    );
    reach.assertReached();
  },
  60000,
);
